#!/usr/bin/env node
// Rebuild the cropped port assets from a local checkout of the pinned reference.
// Usage: node scripts/import-reference.mjs /path/to/street-fighter-2-javascript
// Requires Python 3 with Pillow. No network access or engine session is used.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync, spawnSync } from 'node:child_process';
import vm from 'node:vm';
import { createHash } from 'node:crypto';

const source = resolve(process.argv[2] ?? '');
if (!process.argv[2]) throw new Error('Provide the local reference checkout path.');
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pin = 'e1c9d48a24f446972c941d4bc714f760908c76da';
const sha = execFileSync('git', ['-C', source, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
if (sha !== pin) throw new Error(`Expected reference ${pin}, got ${sha}`);
const trackedInputs = [];
function read(path) { trackedInputs.push(path); return readFileSync(resolve(source, path), 'utf8'); }
function stripImports(s) { return s.replace(/^import\s[\s\S]*?;\s*$/gm, '').replace(/\bexport /g, ''); }
const context = vm.createContext({ FRAME_TIME: 1000 / 60 });
vm.runInContext(stripImports(read('src/constants/fighter.js')), context);
function field(text, key, end) {
  const start = text.indexOf(`    ${key} = `);
  if (start < 0) throw new Error(`Missing ${key}`);
  const from = text.indexOf('=', start) + 1;
  const to = text.indexOf(end, from) + end.length - 1;
  return vm.runInContext(`(${text.slice(from, to)})`, context);
}
const crops = [];
const fighters = ['Ryu', 'Ken'].map(name => {
  const text = read(`src/entities/fighters/${name}.js`);
  const frames = Object.fromEntries([...field(text, 'frames', ']);')].map(([key, [geometry, push, hurt, hit]]) => {
    const [rect, origin] = geometry;
    const sprite = `fighters/${name.toLowerCase()}/${key}`;
    crops.push({ sprite, image: `${name.toLowerCase()}.png`, rect, origin, canvas: [256, 256], pivot: [128, 224] });
    return [key, { sprite, rect, origin, push, hurt, hit: hit ?? [0, 0, 0, 0] }];
  }));
  return { name, frames, animations: field(text, 'animations', '};'), initialVelocity: field(text, 'initialVelocity', '};'), gravity: Number(text.match(/gravity = (\d+)/)[1]) };
});
mkdirSync(resolve(root, 'src/data'), { recursive: true });
writeFileSync(resolve(root, 'src/data/fighters.ts'), `// Generated by scripts/import-reference.mjs; source ${pin}.\nimport type { FighterDefinition } from './fighter-types';\nexport const FIGHTERS: readonly [FighterDefinition, FighterDefinition] = ${JSON.stringify(fighters, null, 2)};\n`);

const stageContext = vm.createContext({ FRAME_TIME: 1000 / 60, document: { querySelector: () => null }, playSound: () => {},
  BackgroundAnimation: class { constructor(image, frames, animation) { this.frames = frames; this.animation = animation; } },
  SkewedFloor: class { constructor(image, rect) { this.rect = rect; } } });
vm.runInContext(stripImports(read('src/entities/stage/KenStage.js')) + ';globalThis.stage = new KenStage();', stageContext);
read('src/entities/stage/shared/SkewedFloor.js');
read('src/entities/fighters/shared/Shadow.js');
const stage = stageContext.stage;
const stageFrames = Object.fromEntries(stage.frames);
stageFrames['stage-floor'] = stage.floor.rect;
const stageAnimations = {};
// Original screen positions before subtracting the vertical camera offset.
// Boat-attached sprites inherit its parallax and bob; flag inherits background parallax.
const stagePlacements = [
  { frame: 'stage-background', x: 16, y: 0, cameraDivisor: 2.157303, layer: 'background' },
  { animation: 'flag', x: 560, y: 16, parent: 'stage-background', layer: 'background' },
  { frame: 'stage-boat', x: 150, y: 0, cameraDivisor: 1.613445, layer: 'boat' },
  { animation: 'baldMan', x: 128, y: 96, parent: 'stage-boat', layer: 'boat' },
  { frames: ['grey-suit-1', 'grey-suit-2'], x: 167, y: 112, parent: 'stage-boat', layer: 'boat' },
  { animation: 'cheeringWoman', x: 192, y: 104, parent: 'stage-boat', layer: 'boat' },
  { animation: 'greenJumperGuy', x: 224, y: 104, parent: 'stage-boat', layer: 'boat' },
  { animation: 'blueCoatGuy', x: 288, y: 96, parent: 'stage-boat', layer: 'boat' },
  { animation: 'purpleJumperGuy', x: 128, y: 24, parent: 'stage-boat', layer: 'boat' },
  { animation: 'brownSuitGuy', x: 88, y: 24, parent: 'stage-boat', layer: 'boat' },
  { frame: 'stage-floor', x: 32, y: 176, cameraDivisor: 1.55, layer: 'floor', shearBase: -5.15, shearCameraOffset: 1024, shearCameraDivisor: 112 },
  { frame: 'stage-floor-bottom', x: 256, y: 232, cameraMultiplier: 1.1, layer: 'floor' },
  { frame: 'bollard-small', x: 376, y: 166, cameraDivisor: 1.54, layer: 'background-props' },
  { frame: 'bollard-small', x: 560, y: 166, cameraDivisor: 1.54, layer: 'background-props' },
  { frame: 'barrels', x: 872, y: 120, cameraDivisor: 1, layer: 'background-props' },
  { frame: 'bollard-large', x: 493, y: 200, cameraDivisor: 0.958, layer: 'foreground' },
  { frame: 'bollard-large', x: 787, y: 200, cameraDivisor: 0.958, layer: 'foreground' },
];
for (const name of ['flag', 'baldMan', 'cheeringWoman', 'greenJumperGuy', 'blueCoatGuy', 'purpleJumperGuy', 'brownSuitGuy']) {
  Object.assign(stageFrames, Object.fromEntries(stage[name].frames));
  stageAnimations[name] = stage[name].animation;
}
for (const [key, rect] of Object.entries(stageFrames)) crops.push({ sprite: `stage/${key}`, image: 'ken-stage.png', rect, key: [83, 103, 141] });
const floorStrips = Array.from({ length: 56 }, (_, row) => `stage/floor-strip-${String(row).padStart(2, '0')}`);
floorStrips.forEach((sprite, row) => crops.push({ sprite, image: 'ken-stage.png', rect: [8, 392 + row, 896, 1] }));
writeFileSync(resolve(root, 'src/data/stage.ts'), `// Generated from KenStage.js. Source rectangles are top-left pixel coordinates.\nexport const STAGE_FRAMES = ${JSON.stringify(Object.fromEntries(Object.entries(stageFrames).map(([key, rect]) => [key, { sprite: `stage/${key}`, rect }])), null, 2)} as const;\n// Durations are source milliseconds (fighter durations use simulation frames).\nexport const STAGE_ANIMATIONS = ${JSON.stringify(stageAnimations, null, 2)} as const;\n// Placement offsets in original pixels; xScreen = x - cameraX / cameraDivisor.\nexport const STAGE_PLACEMENTS = ${JSON.stringify(stagePlacements, null, 2)} as const;\nexport const STAGE_FLOOR_STRIPS = ${JSON.stringify(floorStrips, null, 2)} as const;\n`);

const effectContext = vm.createContext({});
vm.runInContext(stripImports(read('src/entities/fighters/special/Fireball.js')).split('const animations')[0] + ';globalThis.fireFrames=frames;', effectContext);
const projectileFrames = {};
for (const [key, [geometry, hit, hurt]] of effectContext.fireFrames) {
  const [rect, origin] = geometry;
  crops.push({ sprite: `effects/${key}`, image: 'ken.png', rect, origin, canvas: [128, 128], pivot: [64, 64] });
  projectileFrames[key] = { sprite: `effects/${key}`, rect, origin, hit, hurt: hurt ?? [0, 0, 0, 0] };
}
const hitFrames = {};
for (const strength of ['Light', 'Medium', 'Heavy']) {
  const text = read(`src/entities/fighters/shared/${strength}HitSplash.js`);
  const start = text.indexOf('frames = ') + 9;
  const frames = vm.runInNewContext(`(${text.slice(start, text.indexOf('];', start) + 1)})`);
  hitFrames[strength.toLowerCase()] = frames.map(([rect, origin], i) => {
    const sprite = `effects/hit-${strength.toLowerCase()}-${i}`;
    crops.push({ sprite, image: 'decals.png', rect, origin, canvas: [128, 128], pivot: [64, 64], key: [42, 81, 114] });
    return sprite;
  });
}
crops.push({ sprite: 'effects/shadow', image: 'shadow.png', rect: [0, 0, 68, 11], key: [27, 2, 218] });
writeFileSync(resolve(root, 'src/data/effects.ts'), `// Generated by scripts/import-reference.mjs. Effects are centered in 128px squares.\nexport const PROJECTILE_FRAMES = ${JSON.stringify(projectileFrames, null, 2)} as const;\nexport const HIT_FRAMES = ${JSON.stringify(hitFrames, null, 2)} as const;\n`);
vm.runInContext('const TIME_FRAME_KEYS = ["time", "time-flash"];', context);
const hudText = read('src/entities/overlays/StatusBar.js');
const hudFrames = field(hudText, 'frames', ']);');
for (const [key, rect] of hudFrames) crops.push({ sprite: `ui/${key === 'score-@' ? 'score-at' : key}`, image: 'misc.png', rect });

// Additional authentic poses are manually audited in source-sheet pixel coordinates.
// Combat metadata owns their timelines/boxes; this manifest owns only art and feet pivots.
const extraPath = resolve(root, 'scripts/extra-frame-crops.json');
let extraFrames;
if (existsSync(extraPath)) {
  const bytes = readFileSync(extraPath);
  const manifest = JSON.parse(bytes.toString('utf8'));
  const metadata = ['ryu', 'ken'].map(fighter => Object.fromEntries(Object.entries(manifest[fighter] ?? {}).map(([key, frame]) => [key, { sprite: `fighters/${fighter}/${key}`, rect: frame.rect, origin: frame.origin }])));
  writeFileSync(resolve(root, 'src/data/extended-frames.ts'), `// Source-sheet crops inspected in scripts/extra-frame-crops.json; original pixels and feet pivots preserved.\nexport const EXTENDED_FRAMES = ${JSON.stringify(metadata, null, 2)} as const;\n`);
  let count = 0;
  for (const fighter of ['ryu', 'ken']) for (const [key, frame] of Object.entries(manifest[fighter] ?? {})) {
    if (!/^extra-[a-z0-9-]+$/.test(key)) throw new Error(`Invalid extended sprite key ${key}`);
    crops.push({ sprite: `fighters/${fighter}/${key}`, image: `${fighter}.png`, rect: frame.rect, origin: frame.origin, canvas: [256, 256], pivot: [128, 224] });
    count++;
  }
  extraFrames = { manifest: 'scripts/extra-frame-crops.json', sha256: createHash('sha256').update(bytes).digest('hex'), count };
}
const sounds = readdirSync(resolve(source, 'sounds')).filter(p => p.endsWith('.ogg')).sort();
const python = spawnSync('python3', [resolve(root, 'scripts/import-reference-images.py')], { input: JSON.stringify({ root, source, crops, sounds }), encoding: 'utf8' });
if (python.status !== 0) throw new Error(python.stderr || 'Image conversion failed');
const imageInputs = [...new Set(crops.map(c => `images/${c.image}`)), ...sounds.map(s => `sounds/${s}`)];
const inputs = [...new Set([...trackedInputs, ...imageInputs])].sort().map(path => ({ path, sha256: createHash('sha256').update(readFileSync(resolve(source, path))).digest('hex') }));
writeFileSync(resolve(root, 'scripts/reference-provenance.json'), JSON.stringify({ repository: 'https://github.com/iuritorres/street-fighter-2-javascript', commit: sha, extraFrames, license: 'No license file present at pinned commit; reuse permissions unresolved. Street Fighter characters/art/audio remain third-party material.', conversion: { fighterCanvas: [256, 256], fighterFeetPivot: [128, 224], effectCanvas: [128, 128], effectPivot: [64, 64], resampling: 'none', stageBackgroundKey: [83, 103, 141], decalsBackgroundKey: [42, 81, 114], shadowBackgroundKey: [27, 2, 218] }, inputs }, null, 2) + '\n');
console.log(`Imported ${fighters.map(f => Object.keys(f.frames).length).join(' + ')} fighter frames, ${Object.keys(stageFrames).length} stage frames, ${sounds.length} sounds; ${crops.length} cropped sprites.`);
